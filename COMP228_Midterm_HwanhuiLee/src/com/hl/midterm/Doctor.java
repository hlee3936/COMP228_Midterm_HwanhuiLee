package com.hl.midterm;

public class Doctor extends MedicalStaff implements Reportable, Schedulable{
	protected final double consultationFee;
	protected int patientSeen;
	
	public Doctor(int personId, String name, String phoneNumber, int staffId, String department, double monthlySalary,
			double consultationFee, int patientSeen) {
		super(personId, name, phoneNumber, staffId, department, monthlySalary);
		this.consultationFee = consultationFee;
		this.patientSeen = patientSeen;
	}
	
	@Override
	public double calculateMonthlyCompensation() {
		return monthlySalary + (patientSeen * 5);
	}
	
	@Override
	public void displayStaffDetails() {
		System.out.println("Staff ID: " + staffId);
        System.out.println("Name: " + name);
        System.out.println("Department: " + department);
        System.out.println("Monthly Salary: $" + String.format("%.2f", monthlySalary));
        System.out.println("Patients Seen: " + patientSeen);
        System.out.println("Consultation Fee: $" + String.format("%.2f", consultationFee));
        System.out.println("Monthly Compensation: $" + String.format("%.2f", calculateMonthlyCompensation()));
	}
	
	public double calculateConsultationFee() {
		return consultationFee;
	}
	
	public double calculateConsultationFee(double discount) {
		return consultationFee - discount;
	}
	
	public double calculateConsultationFee(double discount, double additionalCharge) {
		return consultationFee - discount + additionalCharge;
	}
	
	@Override
	public void generateReport() {
		System.out.println("Report generated by " + name);
	}
	
	@Override
	public void scheduleAppointment(String appointmentDate) {
		System.out.println("Appointment scheduled by " + name + " on " + appointmentDate);
		
	}
}
